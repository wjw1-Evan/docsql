package io.docsql.jdbc;

import io.docsql.DocsqlException;
import io.docsql.Result;
import java.sql.SQLException;

/** java.sql.Statement over the core native connection. */
public class JdbcStatement implements java.sql.Statement {

    final JdbcConnection conn;
    protected Result current;
    private boolean closed;
    private int queryTimeoutSeconds;
    private long maxRows;
    private java.sql.SQLWarning warnings;
    private final java.util.List<String> batch = new java.util.ArrayList<>();

    JdbcStatement(JdbcConnection conn) {
        this.conn = conn;
    }

    static void checkStatementAttrs(int type, int concurrency) throws SQLException {
        if (type != java.sql.ResultSet.TYPE_FORWARD_ONLY
                && type != java.sql.ResultSet.TYPE_SCROLL_INSENSITIVE) {
            throw JdbcSql.unsupported("only FORWARD_ONLY or SCROLL_INSENSITIVE result sets");
        }
        if (concurrency != java.sql.ResultSet.CONCUR_READ_ONLY) {
            throw JdbcSql.unsupported("only CONCUR_READ_ONLY result sets");
        }
    }

    static void checkGeneratedKeys(int autoGeneratedKeys) throws SQLException {
        if (autoGeneratedKeys != java.sql.Statement.NO_GENERATED_KEYS) {
            throw JdbcSql.unsupported("getGeneratedKeys is not supported by the wire protocol");
        }
    }

    static void checkGeneratedKeysCols(int[] cols) throws SQLException {
        if (cols != null && cols.length > 0) {
            throw JdbcSql.unsupported("getGeneratedKeys is not supported by the wire protocol");
        }
    }

    static void checkGeneratedKeysCols(String[] cols) throws SQLException {
        if (cols != null && cols.length > 0) {
            throw JdbcSql.unsupported("getGeneratedKeys is not supported by the wire protocol");
        }
    }

    protected void checkOpen() throws SQLException {
        if (closed || conn.isClosed()) {
            throw JdbcSql.closed();
        }
    }

    private io.docsql.Result run(String sql) throws SQLException {
        checkOpen();
        try {
            return conn.core().execute(sql);
        } catch (DocsqlException e) {
            SQLException wrapped = JdbcSql.wrap(e);
            SQLException withSql = (SQLException) wrapped.fillInStackTrace();
            throw new java.sql.SQLException(sql + " -> " + wrapped.getMessage(),
                    wrapped.getSQLState(), wrapped.getErrorCode(), wrapped.getCause());
        }
    }

    Result executeReturning(String sql) throws SQLException {
        Result r = run(sql);
        current = r.hasResultSet() ? r : null;
        return r;
    }

    int executeUpdateInternal(String sql) throws SQLException {
        Result r = run(sql);
        if (r.hasResultSet()) {
            throw new SQLException("statement produced a result set", "01000");
        }
        return (int) Math.min(Integer.MAX_VALUE, Math.max(Integer.MIN_VALUE, r.rowcount));
    }

    @Override
    public java.sql.ResultSet executeQuery(String sql) throws SQLException {
        Result r = run(sql);
        if (!r.hasResultSet()) {
            throw new SQLException("statement did not produce a result set", "01000");
        }
        current = r;
        return new JdbcResultSet(this, r);
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        return executeUpdateInternal(sql);
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        checkGeneratedKeys(autoGeneratedKeys);
        return executeUpdateInternal(sql);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        checkGeneratedKeysCols(columnIndexes);
        return executeUpdateInternal(sql);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        checkGeneratedKeysCols(columnNames);
        return executeUpdateInternal(sql);
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        Result r = executeReturning(sql);
        return r.hasResultSet();
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        checkGeneratedKeys(autoGeneratedKeys);
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        checkGeneratedKeysCols(columnIndexes);
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        checkGeneratedKeysCols(columnNames);
        return execute(sql);
    }

    @Override
    public java.sql.ResultSet getResultSet() throws SQLException {
        checkOpen();
        if (current != null && current.hasResultSet()) {
            return new JdbcResultSet(this, current);
        }
        return null;
    }

    @Override
    public int getUpdateCount() throws SQLException {
        checkOpen();
        if (current == null) {
            return -1;
        }
        if (current.hasResultSet()) {
            return -1;
        }
        return (int) Math.min(Integer.MAX_VALUE, Math.max(Integer.MIN_VALUE, current.rowcount));
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        checkOpen();
        current = null;
        return false;
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        return getMoreResults();
    }

    @Override
    public java.sql.ResultSet getGeneratedKeys() throws SQLException {
        checkOpen();
        return new JdbcResultSet(this, new io.docsql.Result());
    }

    @Override
    public void addBatch(String sql) throws SQLException {
        checkOpen();
        batch.add(sql);
    }

    @Override
    public void clearBatch() throws SQLException {
        checkOpen();
        batch.clear();
    }

    @Override
    public int[] executeBatch() throws SQLException {
        checkOpen();
        int[] out = new int[batch.size()];
        try {
            for (int i = 0; i < batch.size(); i++) {
                out[i] = executeUpdateInternal(batch.get(i));
            }
        } finally {
            batch.clear();
        }
        return out;
    }

    @Override
    public void close() throws SQLException {
        closed = true;
    }

    @Override
    public boolean isClosed() throws SQLException {
        return closed;
    }

    @Override
    public int getResultSetHoldability() throws SQLException {
        checkOpen();
        return java.sql.ResultSet.HOLD_CURSORS_OVER_COMMIT;
    }

    @Override
    public int getResultSetType() throws SQLException {
        checkOpen();
        return java.sql.ResultSet.TYPE_SCROLL_INSENSITIVE;
    }

    @Override
    public int getResultSetConcurrency() throws SQLException {
        checkOpen();
        return java.sql.ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public void setMaxFieldSize(int max) throws SQLException {
        checkOpen();
        if (max < 0) {
            throw new SQLException("max field size must be >= 0");
        }
    }

    @Override
    public int getMaxFieldSize() throws SQLException {
        checkOpen();
        return 0;
    }

    @Override
    public void setMaxRows(int max) throws SQLException {
        checkOpen();
        if (max < 0) {
            throw new SQLException("max rows must be >= 0");
        }
        maxRows = max;
    }

    @Override
    public int getMaxRows() throws SQLException {
        checkOpen();
        return (int) Math.min(Integer.MAX_VALUE, maxRows);
    }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        checkOpen();
    }

    @Override
    public int getFetchSize() throws SQLException {
        checkOpen();
        return 0;
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        checkOpen();
        if (direction != java.sql.ResultSet.FETCH_FORWARD
                && direction != java.sql.ResultSet.FETCH_UNKNOWN) {
            throw JdbcSql.unsupported("only FETCH_FORWARD/FETCH_UNKNOWN");
        }
    }

    @Override
    public int getFetchDirection() throws SQLException {
        checkOpen();
        return java.sql.ResultSet.FETCH_FORWARD;
    }

    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        checkOpen();
        if (seconds < 0) {
            throw new SQLException("query timeout must be >= 0");
        }
        queryTimeoutSeconds = seconds;
    }

    @Override
    public int getQueryTimeout() throws SQLException {
        checkOpen();
        return queryTimeoutSeconds;
    }

    @Override
    public void setEscapeProcessing(boolean enable) throws SQLException {
        checkOpen();
    }

    @Override
    public void setCursorName(String name) throws SQLException {
        throw JdbcSql.unsupported("positioned updates are not supported");
    }

    @Override
    public java.sql.Connection getConnection() throws SQLException {
        return conn;
    }

    @Override
    public java.sql.SQLWarning getWarnings() throws SQLException {
        checkOpen();
        return null;
    }

    @Override
    public void clearWarnings() throws SQLException {
        checkOpen();
    }

    @Override
    public void setPoolable(boolean poolable) throws SQLException {
        checkOpen();
    }

    @Override
    public boolean isPoolable() throws SQLException {
        checkOpen();
        return false;
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        checkOpen();
    }

    @Override
    public boolean isCloseOnCompletion() throws SQLException {
        checkOpen();
        return false;
    }

    @Override
    public void cancel() throws SQLException {
        throw JdbcSql.unsupported("statement cancellation is not supported by the wire protocol");
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        throw new SQLException("not a wrapper for " + iface.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) throws SQLException {
        return iface.isInstance(this);
    }
}
