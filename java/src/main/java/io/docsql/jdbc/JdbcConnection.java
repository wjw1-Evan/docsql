package io.docsql.jdbc;

import io.docsql.DocsqlConnection;
import java.sql.SQLException;

/** java.sql.Connection over the core native connection. */
public final class JdbcConnection implements java.sql.Connection {

    final DocsqlConnection core;
    private boolean closed;

    public JdbcConnection(DocsqlConnection core) {
        this.core = core;
    }

    private void checkOpen() throws SQLException {
        if (closed || core.isClosed()) {
            throw JdbcSql.closed();
        }
    }

    DocsqlConnection core() throws SQLException {
        checkOpen();
        return core;
    }

    @Override
    public java.sql.Statement createStatement() throws SQLException {
        checkOpen();
        return new JdbcStatement(this);
    }

    @Override
    public java.sql.Statement createStatement(int resultSetType, int resultSetConcurrency)
            throws SQLException {
        JdbcStatement.checkStatementAttrs(resultSetType, resultSetConcurrency);
        return createStatement();
    }

    @Override
    public java.sql.Statement createStatement(int resultSetType, int resultSetConcurrency,
            int resultSetHoldability) throws SQLException {
        return createStatement(resultSetType, resultSetConcurrency);
    }

    @Override
    public java.sql.PreparedStatement prepareStatement(String sql) throws SQLException {
        checkOpen();
        return new JdbcPreparedStatement(this, sql);
    }

    @Override
    public java.sql.PreparedStatement prepareStatement(String sql, int resultSetType,
            int resultSetConcurrency) throws SQLException {
        JdbcStatement.checkStatementAttrs(resultSetType, resultSetConcurrency);
        return prepareStatement(sql);
    }

    @Override
    public java.sql.PreparedStatement prepareStatement(String sql, int resultSetType,
            int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        return prepareStatement(sql, resultSetType, resultSetConcurrency);
    }

    @Override
    public java.sql.PreparedStatement prepareStatement(String sql, int autoGeneratedKeys)
            throws SQLException {
        JdbcStatement.checkGeneratedKeys(autoGeneratedKeys);
        return prepareStatement(sql);
    }

    @Override
    public java.sql.PreparedStatement prepareStatement(String sql, int[] columnIndexes)
            throws SQLException {
        JdbcStatement.checkGeneratedKeysCols(columnIndexes);
        return prepareStatement(sql);
    }

    @Override
    public java.sql.PreparedStatement prepareStatement(String sql, String[] columnNames)
            throws SQLException {
        JdbcStatement.checkGeneratedKeysCols(columnNames);
        return prepareStatement(sql);
    }

    @Override
    public java.sql.CallableStatement prepareCall(String sql) throws SQLException {
        throw JdbcSql.feature("CallableStatement / stored procedures are not supported");
    }

    @Override
    public java.sql.CallableStatement prepareCall(String sql, int resultSetType,
            int resultSetConcurrency) throws SQLException {
        throw JdbcSql.feature("CallableStatement / stored procedures are not supported");
    }

    @Override
    public java.sql.CallableStatement prepareCall(String sql, int resultSetType,
            int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        throw JdbcSql.feature("CallableStatement / stored procedures are not supported");
    }

    @Override
    public String nativeSQL(String sql) throws SQLException {
        core();
        return sql;
    }

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException {
        core().setAutocommit(autoCommit);
    }

    @Override
    public boolean getAutoCommit() throws SQLException {
        return core().isAutocommit();
    }

    @Override
    public void commit() throws SQLException {
        core().commit();
    }

    @Override
    public void rollback() throws SQLException {
        core().rollback();
    }

    @Override
    public void close() throws SQLException {
        if (closed) {
            return;
        }
        closed = true;
        core.close();
    }

    @Override
    public boolean isClosed() {
        return closed || core.isClosed();
    }

    @Override
    public java.sql.DatabaseMetaData getMetaData() throws SQLException {
        checkOpen();
        return new JdbcDatabaseMetaData(this);
    }

    @Override
    public void setReadOnly(boolean readOnly) throws SQLException {
        core();
        // no wire equivalent: accepted and ignored, like the T-SQL session shims
    }

    @Override
    public boolean isReadOnly() throws SQLException {
        core();
        return false;
    }

    @Override
    public void setCatalog(String catalog) throws SQLException {
        core(); // a DocSQL node IS the database; catalogs do not exist
    }

    @Override
    public String getCatalog() throws SQLException {
        core();
        return null;
    }

    @Override
    public void setTransactionIsolation(int level) throws SQLException {
        core();
        if (level != java.sql.Connection.TRANSACTION_READ_COMMITTED
                && level != java.sql.Connection.TRANSACTION_NONE) {
            throw JdbcSql.unsupported("only READ_COMMITTED isolation is supported");
        }
    }

    @Override
    public int getTransactionIsolation() throws SQLException {
        core();
        return java.sql.Connection.TRANSACTION_READ_COMMITTED;
    }

    @Override
    public java.sql.SQLWarning getWarnings() throws SQLException {
        core();
        return null;
    }

    @Override
    public void clearWarnings() throws SQLException {
        core();
    }

    // -- savepoints (engine SAVEPOINT SQL) ------------------------------------

    private int savepointSeq;

    @Override
    public java.sql.Savepoint setSavepoint() throws SQLException {
        core();
        String name = "DOCSQL_SVPT_" + (++savepointSeq);
        try (JdbcStatement st = new JdbcStatement(this)) {
            st.executeUpdateInternal("SAVEPOINT " + name);
        }
        return new JdbcSavepoint(name, 0);
    }

    @Override
    public java.sql.Savepoint setSavepoint(String name) throws SQLException {
        core();
        String q = "DOCSQL_SVPT_" + (++savepointSeq) + "_" + name;
        try (JdbcStatement st = new JdbcStatement(this)) {
            st.executeUpdateInternal("SAVEPOINT " + quoteIdent(q));
        }
        return new JdbcSavepoint(q, 0);
    }

    @Override
    public void rollback(java.sql.Savepoint savepoint) throws SQLException {
        core();
        try (JdbcStatement st = new JdbcStatement(this)) {
            st.executeUpdateInternal("ROLLBACK TO SAVEPOINT " + quoteIdent(savepoint.getSavepointName()));
        }
    }

    @Override
    public void releaseSavepoint(java.sql.Savepoint savepoint) throws SQLException {
        core();
        try (JdbcStatement st = new JdbcStatement(this)) {
            st.executeUpdateInternal("RELEASE SAVEPOINT " + quoteIdent(savepoint.getSavepointName()));
        }
    }

    private static String quoteIdent(String s) {
        return '"' + s.replace("\"", "\"\"") + '"';
    }

    static final class JdbcSavepoint implements java.sql.Savepoint {
        private final String name;
        private final int id;

        JdbcSavepoint(String name, int id) {
            this.name = name;
            this.id = id;
        }

        @Override
        public int getSavepointId() {
            return id;
        }

        @Override
        public String getSavepointName() {
            return name;
        }
    }

    // -- remaining interface surface -------------------------------------------

    @Override
    public java.sql.Clob createClob() throws SQLException {
        throw JdbcSql.feature("LOB locators are not supported; use byte[] parameters");
    }

    @Override
    public java.sql.Blob createBlob() throws SQLException {
        throw JdbcSql.feature("LOB locators are not supported; use byte[] parameters");
    }

    @Override
    public java.sql.NClob createNClob() throws SQLException {
        throw JdbcSql.feature("LOB locators are not supported; use byte[] parameters");
    }

    @Override
    public java.sql.SQLXML createSQLXML() throws SQLException {
        throw JdbcSql.feature("SQLXML is not supported");
    }

    @Override
    public java.sql.Array createArrayOf(String typeName, Object[] elements) throws SQLException {
        throw JdbcSql.feature("createArrayOf is not supported");
    }

    @Override
    public java.sql.Struct createStruct(String typeName, Object[] attributes) throws SQLException {
        throw JdbcSql.feature("createStruct is not supported");
    }

    @Override
    public boolean isValid(int timeout) {
        try {
            core.ping();
            return true;
        } catch (RuntimeException e) {
            return false;
        }
    }

    @Override
    public void setClientInfo(String name, String value) throws java.sql.SQLClientInfoException {
        // accepted and ignored
    }

    @Override
    public void setClientInfo(java.util.Properties properties)
            throws java.sql.SQLClientInfoException {
        // accepted and ignored
    }

    @Override
    public String getClientInfo(String name) throws SQLException {
        core();
        return null;
    }

    @Override
    public java.util.Properties getClientInfo() throws SQLException {
        core();
        return new java.util.Properties();
    }

    @Override
    public void setHoldability(int holdability) throws SQLException {
        core();
        if (holdability != java.sql.ResultSet.HOLD_CURSORS_OVER_COMMIT) {
            throw JdbcSql.unsupported("only HOLD_CURSORS_OVER_COMMIT is supported");
        }
    }

    @Override
    public int getHoldability() throws SQLException {
        core();
        return java.sql.ResultSet.HOLD_CURSORS_OVER_COMMIT;
    }

    @Override
    public int getNetworkTimeout() throws SQLException {
        core();
        return core.config.timeoutMs;
    }

    @Override
    public void setNetworkTimeout(java.util.concurrent.Executor executor, int milliseconds)
            throws SQLException {
        core();
        if (milliseconds < 0) {
            throw new SQLException("network timeout must be >= 0");
        }
        // applied per operation by the transport's timeout discipline
    }

    @Override
    public void setSchema(String schema) throws SQLException {
        core(); // no schemas
    }

    @Override
    public String getSchema() throws SQLException {
        core();
        return null;
    }

    @Override
    public void abort(java.util.concurrent.Executor executor) throws SQLException {
        close();
    }

    @Override
    public java.util.Map<String, Class<?>> getTypeMap() throws SQLException {
        core();
        return new java.util.HashMap<>();
    }

    @Override
    public void setTypeMap(java.util.Map<String, Class<?>> map) throws SQLException {
        core(); // accepted and ignored
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        throw new SQLException("not a wrapper for " + iface.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) throws SQLException {
        return iface.isInstance(this);
    }
}
