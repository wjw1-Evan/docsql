//! "Switch your program's database to DocSQL" — dialect ingestion matrix for
//! PostgreSQL, SQLite and Oracle.
//!
//! Each test pins one of two contracts:
//! * the everyday DDL/DML surface of the source dialect imports and behaves
//!   like the source database (auto keys, upserts, casts, functions), or
//! * a construct that cannot be honored fails **loudly** — never silently
//!   dropped or degraded (see AGENTS red line 18).

use super::*;

fn run(db: &mut Database, sql: &str) -> ExecOutcome {
    db.execute(sql)
        .unwrap_or_else(|e| panic!("SQL failed: {sql}\n{e}"))
}

fn rows(db: &mut Database, sql: &str) -> QueryResult {
    match run(db, sql) {
        ExecOutcome::Rows(r) => r,
        other => panic!("expected rows, got {other:?}"),
    }
}

fn err_of(db: &mut Database, sql: &str) -> String {
    match db.execute(sql) {
        Ok(other) => panic!("expected a loud rejection for: {sql}\n got {other:?}"),
        Err(e) => e.to_string(),
    }
}

/// PostgreSQL auto keys: `SERIAL` / `BIGSERIAL` and the modern
/// `GENERATED … AS IDENTITY` all collapse onto the engine's AUTOINCREMENT so
/// inserts that omit the key behave like the source database (before this,
/// SERIAL was accepted as a *type* and silently inserted NULL ids).
#[test]
fn postgres_serial_and_identity_keys_generate_ids() {
    let mut db = Database::in_memory().unwrap();
    run(
        &mut db,
        "CREATE TABLE users (id SERIAL PRIMARY KEY, email TEXT NOT NULL UNIQUE)",
    );
    run(&mut db, "INSERT INTO users (email) VALUES ('a@x'), ('b@x')");
    let r = rows(&mut db, "SELECT id FROM users ORDER BY id");
    assert_eq!(r.rows, vec![vec![Value::Int(1)], vec![Value::Int(2)]]);

    run(
        &mut db,
        "CREATE TABLE audit (id BIGSERIAL PRIMARY KEY, note TEXT)",
    );
    run(&mut db, "INSERT INTO audit (note) VALUES ('x')");
    assert_eq!(
        rows(&mut db, "SELECT id FROM audit"),
        QueryResult {
            columns: vec!["id".into()],
            rows: vec![vec![Value::Int(1)]],
        }
    );

    run(
        &mut db,
        "CREATE TABLE modern (id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v TEXT)",
    );
    run(&mut db, "INSERT INTO modern (v) VALUES ('m1'), ('m2')");
    let r = rows(&mut db, "SELECT COUNT(DISTINCT id) FROM modern");
    assert_eq!(r.rows, vec![vec![Value::Int(2)]]);

    // Oracle spelling (BY DEFAULT ON NULL) flattens the same way.
    run(
        &mut db,
        "CREATE TABLE legacy (id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, v VARCHAR2(20))",
    );
    run(&mut db, "INSERT INTO legacy (v) VALUES ('o')");
    assert_eq!(
        rows(&mut db, "SELECT id FROM legacy"),
        QueryResult {
            columns: vec!["id".into()],
            rows: vec![vec![Value::Int(1)]],
        }
    );
}

/// PostgreSQL everyday query surface: `now()`, `::` casts, `ILIKE`,
/// `ON CONFLICT (col) DO UPDATE … EXCLUDED` (pg_dump's upsert form),
/// `RETURNING`, `LIMIT/OFFSET` and `FILTER`.
#[test]
fn postgres_query_surface_imports_and_runs() {
    let mut db = Database::in_memory().unwrap();
    run(
        &mut db,
        "CREATE TABLE events (id INT AUTOINCREMENT PRIMARY KEY, \
          name TEXT NOT NULL UNIQUE, hits INT NOT NULL, at TIMESTAMP NOT NULL)",
    );
    run(
        &mut db,
        "INSERT INTO events (name, hits, at) VALUES \
         ('Build', 1, now()), ('Deploy', 2, now())",
    );

    // :: casts (sqlparser parses them as Cast expressions).
    let r = rows(
        &mut db,
        "SELECT (hits + 1)::text AS txt, (hits)::int AS n FROM events WHERE name = 'Build'",
    );
    assert_eq!(r.rows, vec![vec![Value::Str("2".into()), Value::Int(1)]]);

    // ILIKE on the migration's lookup queries.
    let r = rows(
        &mut db,
        "SELECT name FROM events WHERE name ILIKE '%build%'",
    );
    assert_eq!(r.rows, vec![vec![Value::Str("Build".into())]]);

    // pg_dump's upsert shape, including EXCLUDED.
    run(
        &mut db,
        "INSERT INTO events (name, hits, at) VALUES ('Build', 9, now()) \
         ON CONFLICT (name) DO UPDATE SET hits = EXCLUDED.hits",
    );
    let r = rows(&mut db, "SELECT hits FROM events WHERE name = 'Build'");
    assert_eq!(r.rows, vec![vec![Value::Int(9)]]);

    // RETURNING + LIMIT/OFFSET + FILTER stay usable.
    let r = rows(
        &mut db,
        "INSERT INTO events (name, hits, at) VALUES ('Test', 1, now()) RETURNING id",
    );
    assert_eq!(r.rows.len(), 1);
    let r = rows(
        &mut db,
        "SELECT name FROM events ORDER BY id LIMIT 1 OFFSET 1",
    );
    assert_eq!(r.rows, vec![vec![Value::Str("Deploy".into())]]);
    let r = rows(
        &mut db,
        "SELECT COUNT(*) FILTER (WHERE hits > 1) FROM events",
    );
    assert_eq!(r.rows, vec![vec![Value::Int(2)]]);
}

/// pg_dump-only artifacts have no DocSQL equivalent; each one is a loud
/// rejection the migration runbook tells users to strip.
#[test]
fn postgres_dump_only_constructs_are_loud() {
    let mut db = Database::in_memory().unwrap();
    assert!(err_of(&mut db, "SELECT $$dollar body$$").contains("unsupported literal"));
    assert!(err_of(&mut db, "SELECT setval('users_id_seq', 100)").contains("unknown function"));
    assert!(!err_of(&mut db, "CREATE SEQUENCE users_id_seq START WITH 1").is_empty());
    assert!(!err_of(&mut db, "ALTER SEQUENCE users_id_seq OWNED BY users.id").is_empty());
}

/// SQLite ingestion: AUTOINCREMENT, `INSERT OR REPLACE`, `ON CONFLICT DO
/// NOTHING`, `PRAGMA` shims and the `sqlite_master` compatibility view.
#[test]
fn sqlite_dump_surface_imports_and_runs() {
    let mut db = Database::in_memory().unwrap();
    run(&mut db, "PRAGMA user_version = 3");
    run(
        &mut db,
        "CREATE TABLE notes (id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT, tag TEXT UNIQUE)",
    );
    run(
        &mut db,
        "INSERT OR REPLACE INTO notes (body, tag) VALUES ('first', 'x')",
    );
    run(
        &mut db,
        "INSERT OR REPLACE INTO notes (id, body, tag) VALUES (1, 'first v2', 'x')",
    );
    let r = rows(&mut db, "SELECT id, body FROM notes");
    assert_eq!(
        r.rows,
        vec![vec![Value::Int(1), Value::Str("first v2".into())]]
    );

    run(
        &mut db,
        "INSERT INTO notes (body, tag) VALUES ('dup', 'x') ON CONFLICT (tag) DO NOTHING",
    );
    let r = rows(&mut db, "SELECT COUNT(*) FROM notes");
    assert_eq!(r.rows, vec![vec![Value::Int(1)]]);

    // The compatibility view the SQLite driver's introspection rides on.
    let r = rows(
        &mut db,
        "SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'notes'",
    );
    assert_eq!(r.rows, vec![vec![Value::Str("notes".into())]]);
}

/// SQLite's `datetime('now')` is a dialect function this engine does not
/// implement; it must fail loudly rather than bind NULL.
#[test]
fn sqlite_datetime_function_is_loud() {
    let mut db = Database::in_memory().unwrap();
    run(
        &mut db,
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT)",
    );
    let e = err_of(&mut db, "INSERT INTO t (v) VALUES (datetime('now'))");
    assert!(e.contains("unknown function"), "{e}");
}

/// Oracle ingestion: NUMBER/VARCHAR2/DATE types, NVL, DUAL/ROWNUM and bare
/// SYSDATE (rewritten to NOW so write-path wall-clock folding keeps
/// replication deterministic).
#[test]
fn oracle_dump_surface_imports_and_runs() {
    let mut db = Database::in_memory().unwrap();
    run(
        &mut db,
        "CREATE TABLE emp (id NUMBER PRIMARY KEY, name VARCHAR2(40), hired DATE)",
    );
    run(
        &mut db,
        "INSERT INTO emp (id, name, hired) VALUES (1, 'alice', SYSDATE)",
    );
    run(
        &mut db,
        "INSERT INTO emp (id, name, hired) VALUES (2, NULL, SYSDATE)",
    );

    let r = rows(
        &mut db,
        "SELECT NVL(name, 'anonymous') FROM emp ORDER BY id",
    );
    assert_eq!(
        r.rows,
        vec![
            vec![Value::Str("alice".into())],
            vec![Value::Str("anonymous".into())],
        ]
    );

    // SYSDATE imported as a real timestamp value.
    let r = rows(&mut db, "SELECT hired FROM emp WHERE id = 1");
    assert!(
        matches!(r.rows[0][0], Value::Timestamp(_)),
        "{:?}",
        r.rows[0][0]
    );

    // DUAL + ROWNUM pagination idiom.
    let r = rows(&mut db, "SELECT id FROM emp WHERE ROWNUM <= 1 ORDER BY id");
    assert_eq!(r.rows, vec![vec![Value::Int(1)]]);
    assert_eq!(rows(&mut db, "SELECT 1 FROM DUAL").rows.len(), 1);
}

/// Oracle sequences (`seq.NEXTVAL`, `seq.CURRVAL`) are not sequences here:
/// loud rejection (the runbook tells users to migrate the key to
/// AUTOINCREMENT / IDENTITY).
#[test]
fn oracle_sequence_references_are_loud() {
    let mut db = Database::in_memory().unwrap();
    let e = err_of(&mut db, "SELECT emp_seq.NEXTVAL FROM DUAL");
    assert!(e.contains("sequence"), "{e}");
    assert!(e.contains("AUTOINCREMENT"), "{e}");
    // currval too.
    let e = err_of(&mut db, "SELECT emp_seq.currval FROM DUAL");
    assert!(e.contains("sequence"), "{e}");
}

/// MySQL / standard scalar surface programs reach for every day:
/// `IF`, `LOCATE`, `CHAR_LENGTH`/`CHARACTER_LENGTH`, `OCTET_LENGTH`,
/// `MOD`, `POW`, `TRUNCATE` and the standard `POSITION(x IN y)`.
/// All count characters (not bytes) where a position is returned.
#[test]
fn mysql_and_standard_scalar_functions_import_and_run() {
    let mut db = Database::in_memory().unwrap();

    // IF is lazy: the untaken branch is never evaluated (CAST('x' AS INT)
    // would be a loud conversion error).
    let r = rows(
        &mut db,
        "SELECT IF(1 = 1, 'yes', CAST('x' AS INT)) AS a, \
                IF(0, 'yes', 'no') AS b, IF(NULL, 'yes', 'no') AS c, \
                IF(3, 'truthy', 'falsy') AS d",
    );
    assert_eq!(
        r.rows,
        vec![vec![
            Value::Str("yes".into()),
            Value::Str("no".into()),
            Value::Str("no".into()),
            Value::Str("truthy".into()),
        ]]
    );

    // Character positions (1-based, 0 when absent), UTF-8 safe.
    let r = rows(
        &mut db,
        "SELECT LOCATE('c', 'abc') AS a, LOCATE('c', 'abcabc', 4) AS b, \
                LOCATE('z', 'abc') AS c, POSITION('好' IN '你好世界') AS d, \
                POSITION('z' IN 'abc') AS e",
    );
    assert_eq!(
        r.rows,
        vec![vec![
            Value::Int(3),
            Value::Int(6),
            Value::Int(0),
            Value::Int(2),
            Value::Int(0),
        ]]
    );

    // Lengths: characters vs bytes.
    let r = rows(
        &mut db,
        "SELECT CHAR_LENGTH('你好a') AS a, CHARACTER_LENGTH('你好a') AS b, \
                OCTET_LENGTH('你好a') AS c",
    );
    assert_eq!(
        r.rows,
        vec![vec![Value::Int(3), Value::Int(3), Value::Int(7)]]
    );

    // MOD mirrors `%` exactly (NULL on zero, exact for DECIMAL).
    let r = rows(
        &mut db,
        "SELECT MOD(7, 3) AS a, MOD(-7, 3) AS b, \
                MOD(CAST('7.5' AS DECIMAL), 2) AS c",
    );
    assert_eq!(
        r.rows,
        vec![vec![
            Value::Int(1),
            Value::Int(-1),
            Value::Decimal("1.5".parse().unwrap()),
        ]]
    );
    let r = rows(&mut db, "SELECT MOD(7, 0) AS z");
    assert_eq!(r.rows, vec![vec![Value::Null]]);

    // POW is POWER; TRUNCATE cuts toward zero (never rounds).
    let r = rows(
        &mut db,
        "SELECT POW(2, 10) AS a, TRUNCATE(CAST('1.239' AS DECIMAL), 2) AS b, \
                TRUNCATE(123, -1) AS c, TRUNCATE(NULL, 2) AS d",
    );
    assert_eq!(
        r.rows,
        vec![vec![
            Value::Int(1024),
            Value::Decimal("1.23".parse().unwrap()),
            Value::Int(120),
            Value::Null,
        ]]
    );
}
